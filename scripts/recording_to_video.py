#!/usr/bin/env python3
"""
Xournal++ Recording to Video/GIF Converter

This script reads a recording JSON file generated by Xournal++ and
converts it to a video or GIF using Cairo and ffmpeg.

Usage:
    python recording_to_video.py recording.json output.mp4 [--fps 30] [--width 1920] [--height 1080]
    python recording_to_video.py recording.json output.gif [--fps 15] [--width 800] [--height 600]

Requirements:
    - Python 3.7+
    - pycairo
    - Pillow (PIL)
    - ffmpeg (for video output)
"""

